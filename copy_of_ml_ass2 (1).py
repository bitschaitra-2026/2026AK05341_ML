if target_col in data_clean.columns:
    # Split features and target from the DataFrame
    X = data_clean.drop(columns=[target_col])
    y = data_clean[target_col]

    # Handle non-numeric columns like 'datetime'
    if 'datetime' in X.columns:
        X = X.drop(columns=['datetime'])

    # One-hot encode remaining categorical columns
    X = pd.get_dummies(X, drop_first=True)

    # Get feature names for plotting
    feature_names = list(X.columns)
    class_names = ['Not Churned', 'Churned']

    #Splitting the data
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.3, random_state=99)

    #Defining the model
    clf = DecisionTreeClassifier(random_state=1)

    #training Model
    clf.fit(X_train, y_train)

    #making predictions
    y_pred = clf.predict(X_test)
    accuracy = accuracy_score(y_test, y_pred)
    print(f'Initial Accuracy: {accuracy:.4f}')

    #Hyperparameter Tuning with Decision Tree Classifier using GridSearchCV
    param_grid = {
        'max_depth': range(1, 10, 2),
        'min_samples_leaf': range(1, 20, 4),
        'min_samples_split': range(2, 20, 4),
        'criterion': ["entropy", "gini"]
    }

    tree = DecisionTreeClassifier(random_state=1)

    grid_search = GridSearchCV(estimator=tree, param_grid=param_grid,
                               cv=5, verbose=True)
    grid_search.fit(X_train, y_train)

    print("Best cross-validation accuracy:", grid_search.best_score_)
    print("Best parameters:", grid_search.best_params_)

    #Visualizing the Decision Tree Classifier
    tree_clf = grid_search.best_estimator_
    plt.figure(figsize=(18, 15))
    plot_tree(tree_clf, filled=True, feature_names=feature_names,
              class_names=class_names, max_depth=3) # limiting depth in visualization for clarity
    plt.show()
