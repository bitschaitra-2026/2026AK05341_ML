import streamlit as st
import pandas as pd
import joblib
from sklearn.metrics import accuracy_score, roc_auc_score, precision_score, recall_score, f1_score, matthews_corrcoef, confusion_matrix
import matplotlib.pyplot as plt
import seaborn as sns

st.title("E-Commerce Classification Model Evaluator")

# 1. Dataset upload option (Test data CSV)
st.sidebar.header("Upload Test Data")
uploaded_file = st.sidebar.file_uploader("Upload your test dataset (CSV)", type=["csv"])

if uploaded_file is not None:
    test_df = pd.read_csv(uploaded_file)
    st.write("### Test Dataset Preview", test_df.head())

    # Assuming the target column name (update 'Target' to your actual target column name)
    target_column = st.sidebar.selectbox("Select Target Column", test_df.columns)

    X_test = test_df.drop(columns=[target_column])
    y_test = test_df[target_column]

    # 2. Model selection dropdown
    model_name = st.selectbox(
        "Select Classification Model",
        ["Logistic Regression", "Decision Tree", "KNN", "Naive Bayes", "Support Vector Machine"]
    )

    # Map model names to saved files (ensure these files exist in your repo!)
    model_files = {
        "Logistic Regression": "model/logistic_regression.pkl",
        "Decision Tree": "model/decision_tree.pkl",
        "KNN": "model/knn.pkl",
        "Naive Bayes": "model/naive_bayes.pkl",
        "Support Vector Machine": "model/svm.pkl"
    }

    if st.button("Evaluate Model"):
        try:
            # Load the pre-trained model
            model = joblib.load(model_files[model_name])

            # Make predictions without retraining
            y_pred = model.predict(X_test)

            # Calculate metrics required by the assignment
            acc = accuracy_score(y_test, y_pred)
            precision = precision_score(y_test, y_pred, average='weighted', zero_division=0)
            recall = recall_score(y_test, y_pred, average='weighted', zero_division=0)
            f1 = f1_score(y_test, y_pred, average='weighted', zero_division=0)
            mcc = matthews_corrcoef(y_test, y_pred)

            # Try AUC score calculation if binary/probabilities are supported
            try:
                y_prob = model.predict_proba(X_test)
                if y_prob.shape[1] == 2:
                    auc = roc_auc_score(y_test, y_prob[:, 1])
                else:
                    auc = roc_auc_score(y_test, y_prob, multi_class='ovr', average='weighted')
            except Exception:
                auc = "N/A"

            # 3. Display evaluation metrics
            st.write(f"### Results for {model_name}")
            col1, col2, col3 = st.columns(3)
            col1.metric("Accuracy", f"{acc:.4f}")
            col2.metric("Precision", f"{precision:.4f}")
            col3.metric("Recall", f"{recall:.4f}")

            col4, col5, col6 = st.columns(3)
            col4.metric("F1 Score", f"{f1:.4f}")
            col5.metric("MCC Score", f"{mcc:.4f}")
            col6.metric("AUC Score", f"{auc}" if isinstance(auc, str) else f"{auc:.4f}")

            # 4. Confusion Matrix Display
            st.write("### Confusion Matrix")
            fig, ax = plt.subplots(figsize=(6, 4))
            cm = confusion_matrix(y_test, y_pred)
            sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', ax=ax)
            plt.xlabel("Predicted")
            plt.ylabel("Actual")
            st.pyplot(fig)

        except FileNotFoundError:
            st.error(f"Model file for {model_name} not found! Please check your `model/` folder in GitHub.")
else:
    st.info("Please upload your test dataset CSV via the sidebar to begin evaluation.")